<?php

namespace App\Console\Commands;

use App\Jobs\TestHistObatJob;
use App\Models\DetailJadwalObat;
use App\Models\HistoryJadwalObatPasien;
use App\Models\JadwalObat;
use App\Models\JadwalVisit;
use App\Models\LogPenggunaanObat;
use App\Models\Obat;
use App\Models\ObatPasien;
use App\Models\Pasien;
use App\Models\Puskesmas;
use App\Models\User;
use Carbon\Carbon;
use Carbon\CarbonPeriod;
use Google\Service\AirQuality\Resource\History;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Http;

class CreateTestDataCmd extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'app:create-test-data-cmd';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Generate test data';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $this->line('Deleting data...');
        //delete data
        LogPenggunaanObat::truncate();
        HistoryJadwalObatPasien::truncate();
        DetailJadwalObat::truncate();
        JadwalObat::truncate();
        ObatPasien::truncate();
        Pasien::truncate();
        JadwalVisit::truncate();
        User::whereHas('permissions', function ($p) {
            $p->whereIn('name', ['Pasien', 'Pendamping']);
        })->delete();
        Obat::truncate();
        $this->line('Create data pasien...');
        //create data pasien
        $psms = Puskesmas::factory(3)->create();
        foreach ($psms as $p) {
            Pasien::factory(3)->create([
                'puskesmas_id' => $p->id
            ]);
        }
        $psns = Pasien::all();
        //obat
        $this->line('Create data obat...');
        $req = Http::get('https://api.fda.gov/drug/drugsfda.json?limit=50');
        if ($req->ok()) {
            $col = $req->collect();
            $results = $col['results'];
            $bar = $this->output->createProgressBar(count($results));
            foreach ($results as $res) {
                $bar->advance();
                if (isset($res['products'])) {
                    foreach ($res['products'] as $p) {
                        Obat::firstOrCreate([
                            'nama_obat' => $p['brand_name'],
                            'deskripsi' => 'Generated by system'
                        ]);
                    }
                }
            }
            $bar->finish();
        }
        if (Obat::count()) {
            //obat pasien
            $this->line('Create data obat pasien...');
            foreach ($psns as $key =>  $psn) {
                $this->line('[' . ($key + 1) . '/' . count($psns) . '] ' . $psn->nama);
                $per = CarbonPeriod::create($psn->mulai_pengobatan, $psn->selesai_pengobatan, '28 days');
                $obat1 = Obat::inRandomOrder()->first();
                $obat2 = Obat::whereNotIn('id', [$obat1->id])->inRandomOrder()->first();
                $obat3 = Obat::whereNotIn('id', [$obat1->id, $obat2->id])->inRandomOrder()->first();
                foreach ($per as $ky =>  $p) {
                    if ($ky + 1 == count($per)) continue;
                    $this->line('Periode ' . ($ky + 1) . '/' . count($per));
                    $op1 = ObatPasien::create([
                        'obat_id' => $obat1->id,
                        'pasien_id' => $psn->id,
                    ]);
                    $op2 = ObatPasien::create([
                        'obat_id' => $obat2->id,
                        'pasien_id' => $psn->id,
                    ]);
                    $op3 = ObatPasien::create([
                        'obat_id' => $obat3->id,
                        'pasien_id' => $psn->id,
                    ]);
                    foreach ([$op1, $op2, $op3] as $op) {
                        $jadwal = $op->jadwal()->create([
                            'obat_id' => $op->obat_id,
                            'pasien_id' => $op->pasien_id,
                            'mulai_tanggal' => $p,
                            'selesai_tanggal' => $p->clone()->addDay(28),
                            'qty_diberikan' => 3 * 28,
                            'satuan' => 'Tablet',
                        ]);
                        for ($i = 0; $i < 3; $i++) {
                            switch ($i) {
                                case 0:
                                    $waktu = '08:00';
                                    break;
                                case 1:
                                    $waktu = '13:00';
                                    break;
                                case 2:
                                    $waktu = '19:00';
                                    break;
                                default:
                                    $waktu = '09:00';
                                    break;
                            }
                            $jadwal->details()->create([
                                'waktu' => $waktu,
                                'dosis' => 1,
                                'satuan' => 'Tablet',
                            ]);
                        }
                        $endPer = $p->clone()->addDay(28) > Carbon::parse($psn->selesai_pengobatan) ? Carbon::parse($psn->selesai_pengobatan)->endOfDay() : $p->clone()->addDay(28);
                        $per2 = CarbonPeriod::create($p, $endPer, '1 day');
                        foreach ($per2 as $tgl) {
                            foreach ($jadwal->details as $dj) {
                                TestHistObatJob::dispatch($psn, $op, $dj, Carbon::parse($tgl->isoFormat('YYYY-MM-DD') . ' ' . $dj->waktu), $jadwal);
                            }
                        }
                    }
                    JadwalVisit::create([
                        'pasien_id' => $psn->id,
                        'admin_id' => User::whereHas('permissions', function ($p) {
                            $p->where('name', 'Admin');
                        })->inRandomOrder()->first()->id,
                        'tgl_visit' => $p->clone()->addDay(24),
                        'keluhan' => fake('id_ID')->sentence(2),
                        'catatan' => fake('id_ID')->sentence(4),
                        'active' => Carbon::createFromDate($p->clone()->addDay(24))->isPast() ? false : true,
                    ]);
                }
            }
        }
    }
}
