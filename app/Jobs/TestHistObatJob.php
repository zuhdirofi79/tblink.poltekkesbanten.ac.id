<?php

namespace App\Jobs;

use App\Models\DetailJadwalObat;
use App\Models\HistoryJadwalObatPasien;
use App\Models\JadwalObat;
use App\Models\LogPenggunaanObat;
use App\Models\ObatPasien;
use App\Models\Pasien;
use Carbon\Carbon;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Queue\Queueable;

class TestHistObatJob implements ShouldQueue
{
    use Queueable;

    /**
     * Create a new job instance.
     */
    public $psn;
    public $op;
    public $dj;
    public $tgl;
    public $jadwal;
    public function __construct(Pasien $psn, ObatPasien $op, DetailJadwalObat $dj, Carbon $tgl, JadwalObat $jadwal)
    {
        $this->psn = $psn;
        $this->op = $op;
        $this->dj = $dj;
        $this->tgl = $tgl;
        $this->jadwal = $jadwal;
    }

    /**
     * Execute the job.
     */
    public function handle(): void
    {
        $jadwal = $this->jadwal;
        $psn = $this->psn;
        $op = $this->op;
        $dj = $this->dj;
        $tgl = $this->tgl;
        $hist = HistoryJadwalObatPasien::create([
            'pasien_id' => $psn->id,
            'obat_id' => $op->obat_id,
            'detail_jadwal_obat_id' => $dj->id,
            'waktu' => $tgl,
            'dosis' => $dj->dosis,
            'satuan' => $dj->satuan,
            'sudah_minum' => 1,
            'waktu_aktual_minum' => Carbon::parse($tgl)->addMinutes(rand(-30, 110)),

        ]);
        LogPenggunaanObat::create([
            'jadwal_obat_id' => $jadwal->id,
            'jadwal_minum_obat' => $hist->waktu,
            'aktual_minum_obat' => $hist->waktu_aktual_minum,
            'dosis_obat' => $hist->dosis,
            'satuan' => $hist->satuan,
            'catatan' => 'Generated by system',
            'user_id' => $psn->user_id,
        ]);
    }
}
